import framerockRegistry from '../../../../packages/registry/registry.json';
import { StoryProvenance } from './provenance';

export const storyRegistryItems = new WeakMap<ComponentType, string>();

function readDocumentTheme(): 'light' | 'dark' {
  return typeof document !== 'undefined' && document.documentElement.classList.contains('dark') ? 'dark' : 'light';
}

/** Workbench for stories generated by @fumadocs/story. */
export function FoglampStoryPanel(props: WithControlProps) {
  if (!props.presets.length) return null;
  return <StoryProvider {...props}><Workbench /></StoryProvider>;
}

function Workbench() {
  const { displayName, Component, presets, preset, variant, setVariant, frame } = useStory();
  const [surface, setSurface] = useState<'Default' | 'Muted' | 'Dark Lift'>('Default');
  const [inheritedTheme, setInheritedTheme] = useState<'light' | 'dark'>('light');
  const [explicitOverride, setExplicitOverride] = useState<'light' | 'dark' | null>(null);
  const [themeReady, setThemeReady] = useState(false);
  const [revision, setRevision] = useState(0);
  const prevInheritedRef = useRef<'light' | 'dark' | null>(null);
  const resolvedTheme: 'light' | 'dark' = explicitOverride ?? inheritedTheme;
  const appearance = { mode: resolvedTheme, resolved: resolvedTheme, explicitOverride, ready: themeReady, revision };
  const theme = resolvedTheme === 'dark' ? 'Dark' : 'Light';
  const [copied, setCopied] = useState(false);
  const [resetCount, setResetCount] = useState(0);
  const [origin, setOrigin] = useState<string>();
  useEffect(() => {
    setOrigin(window.location.origin);
    const root = document.documentElement;
    const syncParentTheme = () => {
      const nextMode = readDocumentTheme();
      setInheritedTheme(nextMode);
      setThemeReady(true);
      if (prevInheritedRef.current !== nextMode) {
        const hadPrev = prevInheritedRef.current !== null;
        prevInheritedRef.current = nextMode;
        if (hadPrev) setExplicitOverride(null);
        setRevision(r => r + 1);
      }
    };
    syncParentTheme();
    const observer = new MutationObserver(syncParentTheme);
    observer.observe(root, { attributes: true, attributeFilter: ['class', 'style', 'data-theme'] });
    return () => observer.disconnect();
  }, []);
  const slug = (displayName || 'component').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const item = storyRegistryItems.get(Component) ?? slug;
  const provenanceItem = framerockRegistry.items.find((candidate) => candidate.name === item);
  if (!provenanceItem) throw new Error(`No provenance catalog metadata for story registry item "${item}"`);
  const provenanceSourceUrl = (provenanceItem.upstreamUrl ?? provenanceItem.inspirationUrl) || undefined;
  const notUpstream = provenanceItem.provenance === 'tailrocks-original' ? 'This is not an upstream Foglamp source file.' : undefined;
  const url = /^https?:\/\//i.test(item) ? item : origin ? `${origin}/r/${encodeURIComponent(item)}.json` : undefined;
  const argument = url && (/^[a-zA-Z0-9_/:.@%+=,-]+$/.test(url) ? url : `'${url.replace(/'/g, `'\\''`)}'`);
  const command = argument ? `npx shadcn@latest add ${argument}` : undefined;
  return <Card role="region" aria-label="Story workbench" data-source-surface={theme.toLowerCase()} size="sm" className="not-prose gap-0 overflow-hidden py-0">
    <div className="flex flex-wrap items-center gap-1 border-b px-3 py-2">
      {displayName && <span className="mr-auto px-1 text-sm font-medium">{displayName}</span>}
      <div role="tablist" aria-label="Story presets" className="flex min-w-0 gap-1 overflow-x-auto">
        {presets.map(item => <Button key={item.variant} type="button" size="xs" variant={variant === item.variant ? "secondary" : "ghost"} role="tab" aria-selected={variant === item.variant} title={item.description} onClick={() => setVariant(item.variant)}>{item.variant}</Button>)}
      </div>
    </div>
    <div className="flex flex-wrap items-center justify-end gap-2 border-b px-3 py-2">
      <label className="flex items-center gap-2 text-xs text-muted-foreground">Surface <NativeSelect size="sm" aria-label="Preview surface" value={surface} onChange={event => setSurface(event.target.value as typeof surface)}>{['Default', 'Muted', 'Dark Lift'].map(value => <NativeSelectOption key={value}>{value}</NativeSelectOption>)}</NativeSelect></label>
      <div role="group" aria-label="Preview theme" className="flex gap-0.5 rounded-full p-0.5 shadow-(--custom-shadow)">{(['Light', 'Dark'] as const).map(value => <Button key={value} type="button" size="xs" variant={theme === value ? "secondary" : "ghost"} aria-pressed={theme === value} onClick={() => { const next = value.toLowerCase() === 'dark' ? 'dark' : 'light'; setExplicitOverride(next); setRevision(r => r + 1); }}>{value}</Button>)}</div>
    </div>
    {frame ? <FramePreview appearance={appearance} surface={surface} onChildThemeChange={next => setExplicitOverride(next)} /> : <p role="status" className="p-3 text-xs text-muted-foreground">This story has no preview frame.</p>}
    {preset && <Controls key={`${variant}-${resetCount}`} node={preset.controls} onReset={() => { setVariant(variant); setResetCount(count => count + 1); }} />}
    <div className="flex flex-wrap items-center gap-2 border-t px-3 py-2 text-xs">
      <code className="h-8 min-w-0 flex-1 overflow-x-auto whitespace-nowrap leading-4 text-muted-foreground">{command ?? 'Preparing install command…'}</code>
      <Button type="button" size="xs" variant="outline" disabled={!command} onClick={() => { if (command) void navigator.clipboard.writeText(command).then(() => setCopied(true)).catch(() => setCopied(false)); }}>{copied ? 'Copied' : 'Copy'}</Button>
    </div>
    <StoryProvenance registryItem={item} provenanceLabel={provenanceItem.provenanceLabel} sourceUrl={provenanceSourceUrl} repositoryUrl="https://github.com/foglamp-labs/foglamp" foglampWebsite="https://foglamp.dev" creatorWebsite="https://gustavofior.com" notUpstream={notUpstream} />
  </Card>;
}

function FramePreview({ appearance, surface, onChildThemeChange }: { appearance: { mode: 'light' | 'dark'; resolved: 'light' | 'dark'; explicitOverride: 'light' | 'dark' | null; ready: boolean; revision: number }; surface: 'Default' | 'Muted' | 'Dark Lift'; onChildThemeChange: (mode: 'light' | 'dark') => void }) {
  const { frame, displayName } = useStory();
  const instance = useId();
  const connect = useStoryFrame();
  const [element, setElement] = useState<HTMLIFrameElement | null>(null);
  const viewportRef = useRef<HTMLDivElement>(null);
  const [viewportWidth, setViewportWidth] = useState(0);
  useEffect(() => {
    const node = viewportRef.current;
    if (!node) return;
    if (node.clientWidth > 0) setViewportWidth(node.clientWidth);
    const observer = new ResizeObserver(entries => setViewportWidth(entries[0].contentRect.width));
    observer.observe(node);
    return () => observer.disconnect();
  }, [frame?.width]);
  const [unavailable, setUnavailable] = useState(false);
  const ref = useCallback((iframe: HTMLIFrameElement | null) => {
    setElement(iframe);
    if (iframe) return connect(iframe);
  }, [connect]);
  const latest = useRef({ appearance, surface, onChildThemeChange });
  latest.current = { appearance, surface, onChildThemeChange };
  const sequence = useRef(0);
  const send = useCallback(() => {
    try {
      if (!latest.current.appearance.ready) return;
      if (!element?.contentWindow || !frame || new URL(frame.src, location.href).origin !== location.origin) {
        setUnavailable(true);
        return;
      }
      const { appearance, surface } = latest.current;
      const effectiveTheme: 'light' | 'dark' = appearance.explicitOverride ?? readDocumentTheme();
      element.contentWindow.postMessage({ type: 'foglamp-story:appearance', theme: effectiveTheme, surface, sequence: ++sequence.current }, location.origin);
      setUnavailable(false);
    } catch {
      setUnavailable(true);
    }
  }, [element, frame]);
  useEffect(() => {
    if (!element) return;
    const onMessage = (event: MessageEvent) => {
      if (event.origin !== location.origin || event.source !== element.contentWindow) return;
      if (event.data?.type === 'foglamp-story:ready') send();
      else if (event.data?.type === 'foglamp-story:theme-state' && event.data.source === 'child' && event.data.sequence === sequence.current && (event.data.resolved === 'light' || event.data.resolved === 'dark')) {
        latest.current.onChildThemeChange(event.data.resolved);
      }
    };
    window.addEventListener('message', onMessage);
    return () => window.removeEventListener('message', onMessage);
  }, [element, send]);
  useEffect(() => { if (element && appearance.ready) send(); }, [element, send, surface, appearance.ready, appearance.revision]);
  if (!frame) return null;
  const scale = frame.width && viewportWidth > 0 ? Math.min(1, viewportWidth / (frame.width + 2)) : 1;
  const viewport = <div ref={viewportRef} style={frame.width ? { width: '100%', maxWidth: frame.width + 2, aspectRatio: `${frame.width + 2} / ${(frame.height ?? 800) + 2}`, overflow: 'hidden' } : undefined}><iframe ref={ref} onLoad={send} src={`${frame.src}${frame.src.includes('?') ? '&' : '?'}instance=${encodeURIComponent(instance)}&layout=${frame.width ? 'full' : 'center'}`} title={displayName || 'Component preview'} className="block rounded-md squircle:rounded-2xl corner-squircle border border-transparent shadow-(--custom-shadow)" style={frame.width ? { width: frame.width + 2, height: (frame.height ?? 800) + 2, transform: `scale(${scale})`, transformOrigin: 'top left' } : { width: '100%', height: frame.height ?? 320 }} /></div>;
  return <div className="p-3">{frame.Container ? <frame.Container>{viewport}</frame.Container> : viewport}{unavailable && <p role="status" className="mt-2 text-xs text-muted-foreground">Theme and surface controls require a same-origin preview frame.</p>}</div>;
}

function Controls({ node, onReset }: { node: TypeNode; onReset: () => void }) {
  const engine = useDataEngine();
  const args = useStoryArgs();
  const root = node.type === 'intersection' ? node.intersection : node;
  if (root.type !== 'object' || !root.properties.length) return null;
  const set = (name: string, value: unknown) => { engine.init([name]); engine.update([name], value); };
  return <div className="border-t"><div className="flex items-center justify-between px-3 py-2 text-xs font-medium"><span>Props</span><Button type="button" size="xs" variant="ghost" onClick={onReset}>Reset</Button></div><div className="divide-y border-t">{root.properties.map(prop => {
    const value = args[prop.name];
    const type = prop.type;
    const choices = type.type === 'enum' ? type.members : type.type === 'union' && type.types.every(item => item.type === 'literal' || item.type === 'undefined') ? type.types.filter(item => item.type === 'literal').map(item => ({ label: String(item.value), value: item.value })) : null;
    let control: ReactNode;
    if (choices?.length) control = <NativeSelect size="sm" aria-label={prop.name} value={String(value ?? '')} onChange={event => set(prop.name, choices.find(item => String(item.value) === event.target.value)?.value)}><NativeSelectOption value="" disabled>Select</NativeSelectOption>{choices.map(item => <NativeSelectOption key={String(item.value)} value={String(item.value)}>{item.label}</NativeSelectOption>)}</NativeSelect>;
    else if (type.type === 'boolean') control = <Checkbox aria-label={prop.name} checked={Boolean(value)} onCheckedChange={checked => set(prop.name, Boolean(checked))} />;
    else if (type.type === 'string' || type.type === 'number') control = <Input aria-label={prop.name} type={type.type === 'number' ? 'number' : 'text'} value={typeof value === 'string' || typeof value === 'number' ? String(value) : ''} onChange={event => set(prop.name, type.type === 'number' ? event.target.value === '' ? undefined : Number(event.target.value) : event.target.value)} className="h-8 text-xs" />;
    else control = <span className="text-muted-foreground">{type.displayName || type.type}</span>;
    return <div key={prop.name} className="grid grid-cols-2 items-center gap-3 px-3 py-2 text-xs"><span className="font-mono">{prop.name}</span>{control}</div>;
  })}</div></div>;
}
